def login_user():  # Запрашиваем логин и пароль для входа.
    while True:  # Повторяем вход до успешной авторизации.
        login = input("\nЛогин: ").strip()  # Получаем логин пользователя.
        password = input("Пароль: ")  # Получаем пароль без отображения.
        user = auth_service.authenticate(login, password)  # Проверяем данные через сервис.
        if user:  # Проверяем, прошла ли авторизация.
            role_name = auth_service.ROLE_NAMES[user.role]  # Получаем название роли.
            print(f"Вы вошли как {user.login} ({role_name}).")  # Показываем пользователя и роль.
            return user  # Возвращаем авторизованного пользователя.
        print("Неверный логин или пароль. Попробуйте ещё раз.")  # Сообщаем о неудачном входе.


def users_menu(current_user):  # Объявляем меню управления пользователями.
    roles = list(auth_service.ROLE_NAMES.items())  # Получаем коды и названия доступных ролей.

    while True:  # Повторяем меню до выбора возврата.
        print("\n===== Пользователи =====")  # Выводим заголовок меню.
        print("1. Показать пользователей")  # Показываем пункт просмотра.
        print("2. Добавить пользователя")  # Показываем пункт добавления.
        print("3. Изменить роль пользователя")  # Показываем пункт изменения роли.
        print("4. Удалить пользователя")  # Показываем пункт удаления.
        print("0. Назад")  # Показываем пункт возврата.
        choice = input("Выберите действие: ").strip()  # Получаем выбор пользователя.

        if choice == "1":  # Проверяем выбор просмотра.
            users = auth_service.get_all_users()  # Получаем список пользователей.
            print("\nСписок пользователей:")  # Выводим заголовок списка.
            if not users:  # Проверяем, есть ли пользователи.
                print("Пользователей пока нет.")  # Сообщаем, что список пуст.
            for user in users:  # Перебираем пользователей.
                role_name = auth_service.ROLE_NAMES[user.role]  # Получаем человекочитаемое название роли.
                print(f"{user.user_id}. {user.login} — {role_name}")  # Выводим ID, логин и роль.

        elif choice == "2":  # Проверяем выбор добавления пользователя.
            login = input("Введите логин: ").strip()  # Получаем логин нового пользователя.
            password = input("Введите пароль (минимум 6 символов): ")  # Получаем пароль без отображения.
            for index, (_, role_name) in enumerate(roles, start=1):  # Перебираем роли с номерами.
                print(f"{index}. {role_name}")  # Показываем номер и название роли.
            try:  # Начинаем обработку ввода и регистрации.
                role_number = int(input("Выберите номер роли: ").strip())  # Получаем номер выбранной роли.
                if not 1 <= role_number <= len(roles):  # Проверяем допустимый номер роли.
                    raise ValueError("Нет такой роли.")  # Сообщаем о неверном номере роли.
                role_code = roles[role_number - 1][0]  # Получаем код выбранной роли.
                user_id = auth_service.register_user(login, password, role_code)  # Создаём пользователя.
                print(f"Пользователь создан. Его ID: {user_id}")  # Сообщаем об успехе.
            except ValueError as error:  # Обрабатываем неверный ввод или ошибку регистрации.
                print(f"Ошибка: {error}")  # Показываем причину ошибки.

        elif choice == "3":  # Проверяем выбор изменения роли.
            users = auth_service.get_all_users()  # Получаем пользователей для показа ID.
            for user in users:  # Перебираем пользователей.
                role_name = auth_service.ROLE_NAMES[user.role]  # Получаем название текущей роли.
                print(f"{user.user_id}. {user.login} — {role_name}")  # Показываем пользователя и его роль.
            for index, (_, role_name) in enumerate(roles, start=1):  # Перебираем доступные роли.
                print(f"{index}. {role_name}")  # Показываем номер и название роли.
            try:  # Начинаем обработку ввода и изменения роли.
                user_id = int(input("Введите ID пользователя: ").strip())  # Получаем ID пользователя.
                target_user = next((user for user in users if user.user_id == user_id), None)  # Ищем пользователя по ID.
                if not target_user:  # Проверяем, найден ли пользователь.
                    raise ValueError("Пользователь не найден.")  # Сообщаем, что такого пользователя нет.
                role_number = int(input("Введите номер новой роли: ").strip())  # Получаем номер новой роли.
                if not 1 <= role_number <= len(roles):  # Проверяем допустимый номер роли.
                    raise ValueError("Нет такой роли.")  # Сообщаем о неверном номере роли.
                new_role = roles[role_number - 1][0]  # Получаем код новой роли.
                if target_user.role == "admin" and new_role != "admin":  # Проверяем, не снимаем ли роль у администратора.
                    admin_count = sum(user.role == "admin" for user in users)  # Считаем администраторов.
                    if admin_count <= 1:  # Проверяем, не останется ли система без администратора.
                        raise ValueError("Нельзя изменить роль последнего администратора.")  # Защищаем последнего администратора.
                auth_service.user_repository.update_role(user_id, new_role)  # Сохраняем новую роль в базе.
                print("Роль пользователя изменена.")  # Сообщаем об успехе.
            except ValueError as error:  # Обрабатываем неверный ввод или ошибку проверки.
                print(f"Ошибка: {error}")  # Показываем причину ошибки.

        elif choice == "4":  # Проверяем выбор удаления пользователя.
            users = auth_service.get_all_users()  # Получаем пользователей для показа ID.
            for user in users:  # Перебираем пользователей.
                role_name = auth_service.ROLE_NAMES[user.role]  # Получаем название роли.
                print(f"{user.user_id}. {user.login} — {role_name}")  # Показываем пользователя и его роль.
            try:  # Начинаем обработку ввода и удаления.
                user_id = int(input("Введите ID пользователя для удаления: ").strip())  # Получаем ID пользователя.
                target_user = next((user for user in users if user.user_id == user_id), None)  # Ищем пользователя по ID.
                if not target_user:  # Проверяем, найден ли пользователь.
                    raise ValueError("Пользователь не найден.")  # Сообщаем, что такого пользователя нет.
                if target_user.user_id == current_user.user_id:  # Проверяем, не удаляет ли администратор сам себя.
                    raise ValueError("Нельзя удалить свою текущую учётную запись.")  # Запрещаем самоудаление.
                if target_user.role == "admin":  # Проверяем, является ли удаляемый пользователь администратором.
                    admin_count = sum(user.role == "admin" for user in users)  # Считаем администраторов.
                    if admin_count <= 1:  # Проверяем, не останется ли система без администратора.
                        raise ValueError("Нельзя удалить последнего администратора.")  # Защищаем последнего администратора.
                auth_service.user_repository.delete(user_id)  # Удаляем пользователя из базы.
                print("Пользователь удалён.")  # Сообщаем об успехе.
            except ValueError as error:  # Обрабатываем неверный ввод или ошибку проверки.
                print(f"Ошибка: {error}")  # Показываем причину ошибки.

        elif choice == "0":  # Проверяем выбор возврата.
            break  # Выходим из меню пользователей.
        else:  # Обрабатываем неизвестный пункт меню.
            print("Такого пункта нет. Введите число от 0 до 4.")  # Показываем доступные варианты.


